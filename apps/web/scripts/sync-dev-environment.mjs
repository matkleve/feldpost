import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '../../..');
const outFile = path.resolve(__dirname, '../src/environments/environment.dev-secrets.local.ts');

/** Minimal KEY=VALUE parser for repo-root .env files (no dotenv dependency). */
function parseEnvFile(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }
  const entries = {};
  for (const line of readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    entries[key] = value;
  }
  return entries;
}

const merged = {
  ...parseEnvFile(path.join(repoRoot, '.env')),
  ...parseEnvFile(path.join(repoRoot, '.env.local')),
};

const cartoBasemapApiKey = merged.CARTO_BASEMAP_API_KEY?.trim() ?? '';

const fileContent = `/** Auto-generated by apps/web/scripts/sync-dev-environment.mjs — do not commit */
export const devSecretsLocal = {
  cartoBasemapApiKey: ${JSON.stringify(cartoBasemapApiKey)},
};
`;

writeFileSync(outFile, fileContent, 'utf8');
console.log(
  cartoBasemapApiKey
    ? '[sync-dev-environment] CARTO basemap key loaded from .env.local'
    : '[sync-dev-environment] No CARTO_BASEMAP_API_KEY in .env.local — street tiles show the watermark until you add one (see .env.example).',
);
